const CODES = new Set(COUNTRY_CODES);

export function isCountryCode(value: unknown): value is string {
  return typeof value === "string" && CODES.has(value.trim().toUpperCase());
}

export function normaliseCountry(value: string): string {
  return value.trim().toUpperCase();
}

/**
 * The English name for a code, for a form or an invoice.
 *
 * Falls back to the code itself where the runtime has no data for it: a country shown as
 * "TL" is unhelpful, but an invoice that fails to render is worse.
 */
export function countryName(code: string, locale = "en"): string {
  const normalised = normaliseCountry(code);
  try {
    const names = new Intl.DisplayNames([locale], { type: "region" });
    return names.of(normalised) ?? normalised;
  } catch {
    return normalised;
  }
}

/** Countries sorted by name, for a select. */
export function countryOptions(
  locale = "en",
): readonly { readonly code: string; readonly name: string }[] {
  return COUNTRY_CODES.map((code) => ({ code, name: countryName(code, locale) })).sort(
    (a, b) => a.name.localeCompare(b.name, locale),
  );
}
